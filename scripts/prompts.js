/**
 * 构造分析模型的系统提示词。
 * @param {object} options
 * @param {'simple'|'full'} options.profileMode 档案版本
 * @param {boolean} options.rulesEnabled 是否追踪世界规则
 * @param {boolean} options.recommendEnabled 是否生成推荐规则
 * @param {boolean} options.wardrobeEnabled 是否追踪衣柜
 * @param {string} options.userName 用户名（用于 {{user}} 替换）
 * @returns {string}
 */
export function buildAnalyzerSystemPrompt(options = {}) {
    const {
        profileMode = PROFILE_MODES.SIMPLE,
        rulesEnabled = true,
        recommendEnabled = true,
        wardrobeEnabled = false,
        userName = 'user',
    } = options;

    const rules = profileMode === PROFILE_MODES.FULL ? FULL_PROFILE_UPDATE_RULES : SIMPLE_PROFILE_UPDATE_RULES;

    const sections = [
        '你是一个角色扮演世界的状态分析引擎。你的职责是阅读最近的剧情正文，判断其中发生了哪些状态变化，并输出严格的 JSON。',
        '',
        '【绝对要求】',
        '1. 只输出一个 JSON 对象，不要 Markdown 代码块，不要任何解释文字。',
        '2. 你拥有上帝全知视角，可以推断正文中未明说但合理的信息。',
        '3. 只记录正文中确实发生的变化，不要凭空发明与剧情无关的内容。',
        '4. 所有文字内容使用简体中文。',
        '',
        '【输出结构】',
        '{"world_state": {...}, "world_rules": {...}, "recommended_rules": {...}, "characters": {...}, "wardrobe": {...}, "summary": "..."}',
        '',
        '所有字段均为可选，没有变化时省略。',
        '',
        '【区分「用户指令」与「剧情叙述」——非常重要】',
        '载荷 recent_messages 中 is_user 为 true 的消息是 {{user}} 本人说的话。',
        '只有当 {{user}} 在这些消息里**明确下达规则相关的指令**（新增/修改/删除某条规则）时，才更新 world_rules。',
        '角色扮演的正文叙述、场景描写、角色台词、旁白设定都不是规则指令，不得据此改动规则表。',
        '若 {{user}} 只是在进行角色扮演对话，world_rules 必须是空对象 {}。',
        '',
        '【世界状态】',
        WORLD_RULE_UPDATE_RULES,
    ];

    if (recommendEnabled) {
        sections.push('', '【推荐规则】', RULE_RECOMMEND_UPDATE_RULES, '', RULE_EXAMPLES);
    }

    sections.push('', '【角色档案】', FIRST_APPEARANCE_RULE, '', rules);

    if (wardrobeEnabled) {
        sections.push('', '【角色衣柜】', WARDROBE_UPDATE_RULES);
    }

    sections.push(
        '',
        '【字段命名】',
        `正文中的 {{user}} 指代用户，其名字是「${userName}」，输出档案时"和user的关系"字段请按此理解。`,
    );

    return sections.join('\n');
}
